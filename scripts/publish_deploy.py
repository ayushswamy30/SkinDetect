"""Publish the current website and ONNX models to the `deploy` branch, which Render serves.

The deploy branch holds only what the server needs: app.py, web/, src/skinlesion/, models/onnx/ and a
requirements.txt without PyTorch. Render (service "skindetect", branch deploy, auto-deploy on) rebuilds
on every push to it.

Usage:
    uv run python scripts/export_model.py --name <config>    # models/skinlesion.pt
    uv run python scripts/export_onnx.py                     # models/onnx/
    uv run python scripts/publish_deploy.py                  # commit + push the deploy branch
    uv run python scripts/publish_deploy.py --no-push        # commit only

Render service settings (for re-creating it): runtime Python, build `pip install -r requirements.txt`,
start `python app.py --host 0.0.0.0 --port $PORT`, env PYTHON_VERSION=3.12.8, PYTHONPATH=src,
SKINDETECT_TTA=2, SKINDETECT_THREADS=1 (the free tier has a fraction of one CPU).
"""

import argparse
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

from skinlesion.data import ROOT

BRANCH = "deploy"
REQUIREMENTS = """onnxruntime>=1.20
numpy
pillow
fastapi>=0.115
uvicorn>=0.30
python-multipart>=0.0.9
"""
README = """# SkinDetect: deployment branch

Generated by `scripts/publish_deploy.py` for serving only: the website (`web/`), the API, the
PyTorch-free predictor (`src/skinlesion/serving.py`) and the ONNX fold ensemble (`models/onnx/`).
Run with `pip install -r requirements.txt && PYTHONPATH=src python app.py --host 0.0.0.0 --port 7860`.

Research demo, not a medical device. Model trained on HAM10000 (CC BY-NC 4.0).
"""


def git(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--models", type=Path, default=ROOT / "models" / "onnx")
    parser.add_argument("--no-push", action="store_true")
    args = parser.parse_args()
    meta = json.loads((args.models / "meta.json").read_text())
    source = git("rev-parse", "--short", "HEAD")

    with tempfile.TemporaryDirectory() as tmp:
        wt = Path(tmp) / "deploy"
        git("fetch", "origin", BRANCH)
        git("worktree", "add", "-B", BRANCH, str(wt), f"origin/{BRANCH}")
        try:
            for item in wt.iterdir():  # rebuild the tree from scratch
                if item.name != ".git":
                    shutil.rmtree(item) if item.is_dir() else item.unlink()
            ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
            shutil.copytree(ROOT / "src" / "skinlesion", wt / "src" / "skinlesion", ignore=ignore)
            shutil.copytree(ROOT / "web", wt / "web", ignore=ignore)
            shutil.copytree(args.models, wt / "models" / "onnx")
            shutil.copy2(ROOT / "app.py", wt / "app.py")
            (wt / "requirements.txt").write_text(REQUIREMENTS)
            (wt / "README.md").write_text(README)
            git("add", "-A", "-f", cwd=wt)
            if not git("status", "--porcelain", cwd=wt):
                print("deploy branch already up to date")
                return
            cv = meta["metadata"].get("oof") or {}
            msg = (f"Deploy {meta['metadata'].get('name')} ({len(meta['files'])} x {meta['model_name']}) "
                   f"from {source}\n\nOut-of-fold balanced accuracy {cv.get('balanced_acc', float('nan')):.3f}, "
                   f"temperature {meta['temperature']:.2f}.")
            git("commit", "-q", "-m", msg, cwd=wt)
            if not args.no_push:
                git("push", "origin", BRANCH, cwd=wt)
            print(f"{'Committed' if args.no_push else 'Pushed'} {git('rev-parse', '--short', 'HEAD', cwd=wt)} "
                  f"to {BRANCH}: {msg.splitlines()[0]}")
        finally:
            git("worktree", "remove", "--force", str(wt))


if __name__ == "__main__":
    main()
